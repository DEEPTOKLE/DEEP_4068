a, b = 10, 3

print("Add:", a + b)
print("Sub:", a - b)
print("Mul:", a * b)
print("Div:", a / b)
print("Floor:", a // b)
print("Mod:", a % b)
print("Pow:", a ** b)

print("a>b:", a > b)
print("a<b:", a < b)
print("a==b:", a == b)
print("a!=b:", a != b)

x, y = True, False
print("and:", x and y)
print("or:", x or y)
print("not:", not x)